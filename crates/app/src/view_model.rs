    #[test]
    fn selecting_online_device_emits_selection_but_offline_is_ignored() {
        let mut state = model();
        let online = state
            .core
            .devices
            .iter()
            .find(|device| device.online)
            .expect("online device")
            .id
            .clone();
        let offline = state
            .core
            .devices
            .iter()
            .find(|device| !device.online)
            .expect("offline device")
            .id
            .clone();
        assert_eq!(
            state.reduce_action(UserAction::SelectDevice(online.clone())),
            vec![
                UiCommand::SelectDevice(online.clone()),
                UiCommand::SetQuality {
                    device_id: online,
                    quality: QualityPreset::P720,
                },
            ]
        );
        assert!(matches!(&state.overlay, SessionOverlay::Connecting));
        assert!(state
            .reduce_action(UserAction::SelectDevice(offline))
            .is_empty());
    }


    #[test]
    fn stale_stream_events_from_another_device_do_not_replace_the_selected_session() {
        let mut state = model();
        let selected = state.core.selected_device.clone().expect("selected device");
        let inactive = state
            .core
            .devices
            .iter()
            .find(|device| device.id != selected)
            .expect("inactive device")
            .id
            .clone();
        let display = state
            .core
            .devices
            .iter()
            .find(|device| device.id == inactive)
            .and_then(|device| device.displays.first())
            .expect("display")
            .id;
        let dimensions = state.stream_dimensions;
        let overlay = state.overlay.clone();
        state.apply_event(CoreEvent::StreamStarted {
            device_id: inactive.clone(),
            display_id: display,
            width: 854,
            height: 480,
            fps: 30,
        });
        state.apply_event(CoreEvent::StreamReset {
            device_id: inactive.clone(),
            epoch: 99,
            width: 640,
            height: 360,
        });
        state.apply_event(CoreEvent::DecoderReady {
            device_id: inactive.clone(),
        });
        state.apply_event(CoreEvent::SessionEnded {
            device_id: Some(inactive.clone()),
            reason: SessionEndReason::RemoteClosed,
        });
        state.apply_event(CoreEvent::VideoUnavailable {
            device_id: inactive,
        });
        assert_eq!(state.core.selected_device, Some(selected));
        assert_eq!(state.stream_dimensions, dimensions);
        assert_eq!(state.overlay, overlay);
    }

